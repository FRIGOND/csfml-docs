#!/usr/bin/env python3
"""Génère les pages du site qui dépendent des headers et des exemples :
  - site/src/content/docs/<v>/reference/<module>/<header>.mdx   (composant <ApiHeader>)
  - site/src/content/docs/<v>/reference/index.mdx et function-index.mdx
  - site/src/content/docs/<v>/cookbook/<module>/<exemple>.mdx   (depuis examples/*/*/meta.json)
Usage : python3 tools/gen_site_pages.py   (réécrit les pages générées ; ne touche pas aux pages écrites à la main)
"""
import json, os, re, shutil, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "site/src/content/docs")
VERS = {"3.0": "csfml-3.0.0.json", "2.6": "csfml-2.6.1.json"}
MODS = {"system": "System", "window": "Window", "graphics": "Graphics", "audio": "Audio", "network": "Network"}
GEN = "{/* GENERATED by tools/gen_site_pages.py : ne pas modifier à la main */}\n"
kebab = lambda s: re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", s).lower()

def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(text)

def page_of(header):
    p = header.split("/")
    return p[1].lower(), kebab(p[2][:-2])

stats = {}
for v, fname in VERS.items():
    d = os.path.dirname
    api = json.load(open(os.path.join(ROOT, "api", fname)))
    vd = v.replace(".", "-")
    refdir = os.path.join(DOCS, vd, "reference")
    if os.path.isdir(refdir):
        shutil.rmtree(refdir)
    headers = {}
    for f in api["functions"]:
        headers.setdefault(f["header"], [0, 0])[0] += 1
    for t in api["types"]:
        headers.setdefault(t["header"], [0, 0])[1] += 1
    for h in api["variables"]:
        headers.setdefault(h["header"], [0, 0])[1] += 1
    mod_rows = {m: [] for m in MODS}
    for header, (nf, nt) in sorted(headers.items()):
        if header.count("/") < 2:  # Config.h, GPUPreference.h… (pas de fonctions)
            continue
        mod, slug = page_of(header)
        if mod not in MODS:
            continue
        name = header.split("/")[-1]
        title = f"{name[:-2]}"
        desc = f"Référence de {header} (CSFML {api['csfml_version']}) : {nf} fonctions, types et constantes."
        body = (f"---\ntitle: {title}\ndescription: \"{desc}\"\n---\n\n" + GEN +
                "\nimport ApiHeader from '@/components/ApiHeader.astro';\n\n"
                f"<ApiHeader header=\"{header}\" version=\"{v}\" />\n")
        write(os.path.join(refdir, mod, slug + ".mdx"), body)
        mod_rows[mod].append((slug, name, nf, nt))
    # index de la référence
    lines = ["---", "title: Référence", f"description: Référence de l'API de CSFML {api['csfml_version']}, générée depuis les headers.", "---", "", GEN,
             f"Générée depuis les headers de CSFML **{api['csfml_version']}** (outil `tools/gen_api.py`, libclang) : "
             f"**{len(api['functions'])} fonctions**. Les résumés et descriptions de paramètres viennent des commentaires des headers (en anglais). "
             "Les « notes vérifiées » viennent de tests réels (voir `tests/RESULTATS.md`).", "",
             f"[Index alphabétique de toutes les fonctions](/{vd}/reference/function-index/)", ""]
    for m, label in MODS.items():
        if not mod_rows[m]:
            continue
        lines += [f"## {label}", "", "| Header | Fonctions | Types / constantes |", "|---|---|---|"]
        lines += [f"| [{name}](/{vd}/reference/{m}/{slug}/) | {nf} | {nt} |" for slug, name, nf, nt in mod_rows[m]]
        lines.append("")
    write(os.path.join(refdir, "index.mdx"), "\n".join(lines))
    write(os.path.join(refdir, "function-index.mdx"),
          f"---\ntitle: Index des fonctions\ndescription: Toutes les fonctions de CSFML {api['csfml_version']}, par ordre alphabétique.\n---\n\n{GEN}\n"
          f"import ApiIndex from '@/components/ApiIndex.astro';\n\n<ApiIndex version=\"{v}\" />\n")
    stats[v] = (len(api["functions"]), sum(len(r) for r in mod_rows.values()))

# cookbook : une page par exemple et par version
cook = {v: 0 for v in VERS}
for v in VERS:
    shutil.rmtree(os.path.join(DOCS, v.replace(".", "-"), "cookbook"), ignore_errors=True)
for meta_path in sorted(__import__("glob").glob(os.path.join(ROOT, "examples/*/*/meta.json"))):
    ex_dir = os.path.dirname(meta_path)
    mod, name = ex_dir.split(os.sep)[-2:]
    if mod not in MODS:
        continue
    meta = json.load(open(meta_path, encoding="utf-8"))
    for v, fname in VERS.items():
        if not os.path.isfile(os.path.join(ex_dir, v, "main.c")):
            continue
        api = json.load(open(os.path.join(ROOT, "api", fname)))
        have = {f["name"]: f for f in api["functions"]}
        vd = v.replace(".", "-")
        fns = [n for n in meta.get("functions", []) if n in have]
        links = ", ".join(f"[`{n}`](/{vd}/reference/{page_of(have[n]['header'])[0]}/{page_of(have[n]['header'])[1]}/#{n})" for n in fns)
        other = "2-6" if v == "3.0" else "3-0"
        assets = meta.get("assets") or []
        ex = f"examples/{mod}/{name}"
        text = (f"---\ntitle: \"{meta['title']}\"\ndescription: \"{meta['summary']}\"\n---\n\n{GEN}\n"
                "import Example from '@/components/Example.astro';\nimport TestedBadge from '@/components/TestedBadge.astro';\n\n"
                f"<TestedBadge version=\"{v}\" />\n\n{meta['summary']}\n\n"
                f"<Example example=\"{mod}/{name}\" version=\"{v}\" />\n\n"
                "## Compiler et lancer\n\n"
                f"```sh\ngit clone <dépôt> && cd lib_csfml\nmake -C {ex} CSFML={v} CSFML_PREFIX=system   # ou CSFML_PREFIX=$HOME/csfml-{v}\n"
                f"cd {ex} && ./build/{v}/example\n```\n\n"
                + (f"Fichiers nécessaires : {', '.join('`'+a+'`' for a in assets)} (dossier `examples/assets/`).\n\n" if assets else "")
                + f"## Fonctions utilisées\n\n{links or '—'}\n\n"
                f"Même exemple pour l'autre version : [CSFML {other.replace('-', '.')}](/{other}/cookbook/{mod}/{name}/).\n")
        write(os.path.join(DOCS, vd, "cookbook", mod, name + ".mdx"), text)
        cook[v] += 1
print("référence :", stats, "| cookbook :", cook)
